//! Host-wide append-only error ledger (Issue #3778).
//!
//! Records launch failures, hook failures, operation refusals, and daemon
//! faults as daily JSONL under `~/.gwt/logs/errors/`. `errors.list` reads
//! this ledger; a GUI toast is not a source of truth on its own.

use std::{
    collections::BTreeMap,
    fs::{self, OpenOptions},
    io::{self, BufRead, BufReader, Write},
    path::{Path, PathBuf},
};

use chrono::{DateTime, NaiveDate, Utc};
use serde::{Deserialize, Serialize};

pub const SCHEMA_VERSION: u32 = 1;
pub const LEDGER_FILE_PREFIX: &str = "errors";

/// Error classes the PM can query without reconstructing pane output.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ErrorKind {
    LaunchFailure,
    HookFailure,
    OperationRefusal,
    DaemonFault,
    /// An Issues scan stage failed, whether it aborted or continued.
    ScanFailure,
    /// Issue #4087 AC-2: the Issue cache full refresh (or the index rebuild
    /// that follows a cache write) failed. Reported here instead of a
    /// `tracing::warn` line so `errors.list` can tell the PM why Issues
    /// created on GitHub stopped arriving.
    CacheRefreshFailure,
    /// Clipboard/file upload or staging failed without stopping the Agent.
    AttachmentFailure,
    /// Issue #4666: sustained verification contention, for PM observation
    /// only. This does not interrupt the holder or fail its verification.
    VerificationCongestion,
    /// A verification lease exceeded its TTL (Issue #4417).
    VerificationLeaseExpired,
    /// An orphaned verification holder was reclaimed, with its reason.
    VerificationLeaseReclaimed,
    /// A GUI dispatch is still active beyond the long-stall threshold.
    GuiEventLoopStall,
    /// A persisted ledger row could not be decoded. Generated by the reader;
    /// the damaged source is preserved and never assigned to a project.
    LedgerCorruption,
}

/// Optional locators so a ledger row can be triaged back to a launch.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct ErrorTarget {
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub issue: Option<u64>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub window_id: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub session_id: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub project_root: Option<String>,
}

/// Ownership of an error; unknown never borrows the reader's current project.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ErrorScope {
    Project,
    Host,
    Unknown,
}

/// One append-only error row.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(try_from = "ErrorRecordWire")]
pub struct ErrorRecord {
    pub scope: ErrorScope,
    pub schema_version: u32,
    pub id: String,
    pub recorded_at: DateTime<Utc>,
    pub kind: ErrorKind,
    pub message: String,
    #[serde(default)]
    pub target: ErrorTarget,
    /// Project identity captured when the error occurred. Legacy rows keep
    /// `None`: resolving their path now could assign history to a different repo.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub repo_hash: Option<String>,
    /// Kind-specific structured detail (Issue #3541: hook failures carry
    /// `event`, `handler`, `exit_status`, `fail_open`). Values are sanitized
    /// like `message`; older rows without the field still deserialize.
    #[serde(default, skip_serializing_if = "BTreeMap::is_empty")]
    pub context: BTreeMap<String, String>,
}

// Missing scope is a legacy row. Infer only from its recorded locator.
#[derive(Deserialize)]
struct ErrorRecordWire {
    schema_version: u32,
    id: String,
    recorded_at: DateTime<Utc>,
    kind: ErrorKind,
    message: String,
    #[serde(default)]
    target: ErrorTarget,
    #[serde(default)]
    repo_hash: Option<String>,
    #[serde(default)]
    context: BTreeMap<String, String>,
    #[serde(default)]
    scope: Option<ErrorScope>,
}

fn has_project_root(target: &ErrorTarget) -> bool {
    target
        .project_root
        .as_deref()
        .is_some_and(|root| !root.trim().is_empty())
}

impl TryFrom<ErrorRecordWire> for ErrorRecord {
    type Error = &'static str;

    fn try_from(row: ErrorRecordWire) -> Result<Self, Self::Error> {
        let scope = row.scope.unwrap_or(if has_project_root(&row.target) {
            ErrorScope::Project
        } else {
            ErrorScope::Unknown
        });
        if scope == ErrorScope::Project && !has_project_root(&row.target) {
            return Err("project error requires target.project_root");
        }
        Ok(Self {
            scope,
            schema_version: row.schema_version,
            id: row.id,
            recorded_at: row.recorded_at,
            kind: row.kind,
            message: row.message,
            target: row.target,
            repo_hash: row.repo_hash,
            context: row.context,
        })
    }
}

impl ErrorRecord {
    pub fn new(kind: ErrorKind, message: impl Into<String>, target: ErrorTarget) -> Self {
        let repo_hash = target
            .project_root
            .as_deref()
            .filter(|root| !root.trim().is_empty())
            .map(|root| {
                let root = crate::paths::resolve_current_worktree_root(Path::new(root));
                crate::paths::project_scope_hash(&root).to_string()
            });
        let target = sanitize_target(target);
        Self {
            scope: if has_project_root(&target) {
                ErrorScope::Project
            } else {
                ErrorScope::Unknown
            },
            schema_version: SCHEMA_VERSION,
            id: uuid::Uuid::new_v4().to_string(),
            recorded_at: Utc::now(),
            kind,
            message: sanitize_error_message(&message.into()),
            target,
            repo_hash,
            context: BTreeMap::new(),
        }
    }

    /// Record a fault known to belong to the shared host, without inventing a project.
    pub fn new_host(kind: ErrorKind, message: impl Into<String>) -> Self {
        Self {
            scope: ErrorScope::Host,
            ..Self::new(kind, message, ErrorTarget::default())
        }
    }

    /// Attach sanitized structured detail to the row.
    pub fn with_context(mut self, context: BTreeMap<String, String>) -> Self {
        self.context = context
            .into_iter()
            .map(|(key, value)| (key, sanitize_error_message(&value)))
            .collect();
        self
    }
}

/// Append `record` to today's ledger file. Fail-open callers should use
/// [`record_fail_open`].
pub fn record(record: ErrorRecord) -> io::Result<ErrorRecord> {
    record_inner(record, false)
}

/// Append only if no ledger row already has the caller-supplied ID.
/// The check and append share a filesystem lock across dates and processes.
/// Returns the supplied record even when a duplicate prevents appending it.
pub fn record_once(record: ErrorRecord) -> io::Result<ErrorRecord> {
    record_inner(record, true)
}

fn record_inner(record: ErrorRecord, once: bool) -> io::Result<ErrorRecord> {
    if record.scope == ErrorScope::Project && !has_project_root(&record.target) {
        return Err(io::Error::new(
            io::ErrorKind::InvalidInput,
            "project error requires target.project_root",
        ));
    }
    #[cfg(any(test, feature = "test-support"))]
    if crate::test_support::gwt_home_override().is_none() {
        return Ok(record);
    }
    append_record(&record, once)?;
    Ok(record)
}

/// Best-effort record that never fails the originating operation.
pub fn record_fail_open(kind: ErrorKind, message: impl Into<String>, target: ErrorTarget) {
    let record = ErrorRecord::new(kind, message, target);
    if let Err(error) = self::record(record) {
        tracing::warn!(error = %error, "error ledger append failed");
    }
}

/// Return ledger rows at or after `since`, oldest first. Reader-generated
/// corruption diagnostics use the source file's UTC day, retaining overlapping
/// or unknown days conservatively; their timestamp is not a precise event time.
pub fn list_since(since: Option<DateTime<Utc>>) -> io::Result<Vec<ErrorRecord>> {
    #[cfg(any(test, feature = "test-support"))]
    if crate::test_support::gwt_home_override().is_none() {
        return Ok(Vec::new());
    }
    let lock = match open_ledger_lock() {
        Ok(lock) => lock,
        Err(error) if error.kind() == io::ErrorKind::NotFound => return Ok(Vec::new()),
        Err(error) => return Err(error),
    };
    // Do not diagnose a partially written row while an appender holds the ledger.
    fs2::FileExt::lock_shared(&lock)?;
    let _lock = HeldLedgerLock(lock);
    read_ledger_files(since)
}

/// Releases the ledger lock explicitly instead of relying on close: a
/// duplicate of this description (e.g. inherited by a process forked before
/// exec) would otherwise keep the ledger locked after the holder returns.
struct HeldLedgerLock(fs::File);

impl Drop for HeldLedgerLock {
    fn drop(&mut self) {
        let _ = fs2::FileExt::unlock(&self.0);
    }
}

fn ledger_dir() -> PathBuf {
    crate::paths::gwt_error_ledger_dir()
}

fn ledger_path_for_date(date: NaiveDate) -> PathBuf {
    ledger_dir().join(format!("{LEDGER_FILE_PREFIX}.{date}.jsonl"))
}

#[cfg(test)]
type LedgerLockObserver = Box<dyn FnMut(&fs::File)>;

#[cfg(test)]
thread_local! {
    static TEST_LEDGER_LOCK_OBSERVER: std::cell::RefCell<Option<LedgerLockObserver>> =
        const { std::cell::RefCell::new(None) };
}

/// Observe each ledger lock description this thread acquires.
#[cfg(all(test, unix))]
struct ScopedLedgerLockObserver;

#[cfg(all(test, unix))]
impl ScopedLedgerLockObserver {
    fn set(observer: impl FnMut(&fs::File) + 'static) -> Self {
        TEST_LEDGER_LOCK_OBSERVER.with(|slot| *slot.borrow_mut() = Some(Box::new(observer)));
        Self
    }
}

#[cfg(all(test, unix))]
impl Drop for ScopedLedgerLockObserver {
    fn drop(&mut self) {
        TEST_LEDGER_LOCK_OBSERVER.with(|slot| slot.borrow_mut().take());
    }
}

#[cfg(test)]
fn observe_ledger_lock(lock: &fs::File) {
    TEST_LEDGER_LOCK_OBSERVER.with(|slot| {
        if let Some(observer) = slot.borrow_mut().as_mut() {
            observer(lock);
        }
    });
}

fn open_ledger_lock() -> io::Result<fs::File> {
    OpenOptions::new()
        .create(true)
        .truncate(false)
        .read(true)
        .write(true)
        .open(ledger_dir().join("errors.lock"))
}

/// Strip terminal escapes, redact credentials, and bound the length of a
/// message before it reaches the ledger or a user-visible error line.
pub fn sanitize_error_message(message: &str) -> String {
    const MAX_CHARS: usize = 1_000;
    let stripped = crate::process_console::strip_ansi::strip_ansi(message);
    let mut redacted = redact_credentials(&stripped);
    redacted = redacted
        .chars()
        .filter(|ch| !ch.is_control() || *ch == '\n' || *ch == '\t')
        .collect();
    if redacted.chars().count() > MAX_CHARS {
        redacted = redacted.chars().take(MAX_CHARS).collect();
        redacted.push('…');
    }
    redacted
}

/// Remove the known credential forms used by diagnostic sanitization without
/// stripping or truncating otherwise valid authored text.
pub fn redact_credentials(message: &str) -> String {
    redact_secrets(&crate::process_console::redact::redact_line(message))
}

fn sanitize_target(mut target: ErrorTarget) -> ErrorTarget {
    if let Some(window_id) = target.window_id.as_mut() {
        *window_id = sanitize_error_message(window_id);
    }
    if let Some(session_id) = target.session_id.as_mut() {
        *session_id = sanitize_error_message(session_id);
    }
    if let Some(project_root) = target.project_root.as_mut() {
        *project_root = sanitize_error_message(project_root);
    }
    target
}

fn redact_secrets(message: &str) -> String {
    const SENSITIVE: &[&str] = &[
        "ANTHROPIC_API_KEY",
        "OPENAI_API_KEY",
        "GEMINI_API_KEY",
        "GOOGLE_API_KEY",
        "GITHUB_TOKEN",
        "GH_TOKEN",
        "GWT_HOOK_TOKEN",
        "HOOK_TOKEN",
        "Bearer ",
        "bearer ",
    ];
    let mut redacted = message.to_string();
    for needle in SENSITIVE {
        while let Some(index) = redacted.find(needle) {
            let after_key = index + needle.len();
            let rest = &redacted[after_key..];
            let prefix_skip = rest
                .chars()
                .take_while(|ch| matches!(*ch, '=' | ':' | ' '))
                .count();
            let value = &rest[prefix_skip..];
            let value_len = value
                .chars()
                .take_while(|ch| ch.is_ascii_alphanumeric() || matches!(*ch, '-' | '_' | '.'))
                .count();
            let end = after_key + prefix_skip + value_len;
            redacted.replace_range(index..end, "[REDACTED]");
        }
    }
    redacted
}

fn append_record(record: &ErrorRecord, once: bool) -> io::Result<()> {
    let dir = ledger_dir();
    fs::create_dir_all(&dir)?;
    let lock = open_ledger_lock()?;
    // A timed-out operation still needs to append its failure. Only waiting
    // for another writer should consume/refuse the caller's deadline.
    match fs2::FileExt::try_lock_exclusive(&lock) {
        Ok(()) => {}
        Err(error) if crate::operation_deadline::is_lock_contended(&error) => {
            crate::operation_deadline::lock_exclusive(&lock).map_err(|error| {
                io::Error::new(
                    error.kind(),
                    format!("error ledger lock contended: {error}"),
                )
            })?
        }
        Err(error) => return Err(error),
    }
    let _lock = HeldLedgerLock(lock);
    #[cfg(test)]
    observe_ledger_lock(&_lock.0);
    if once
        && read_ledger_files(None)?
            .iter()
            .any(|row| row.id == record.id)
    {
        return Ok(());
    }
    let path = ledger_path_for_date(record.recorded_at.date_naive());
    let mut file = OpenOptions::new().create(true).append(true).open(path)?;
    serde_json::to_writer(&mut file, record).map_err(json_io_error)?;
    file.write_all(b"\n")?;
    Ok(())
}

// Callers hold the ledger lock: shared for listing, exclusive for record_once.
fn read_ledger_files(since: Option<DateTime<Utc>>) -> io::Result<Vec<ErrorRecord>> {
    let dir = ledger_dir();
    let mut paths = match fs::read_dir(&dir) {
        Ok(entries) => entries
            .map(|entry| entry.map(|entry| entry.path()))
            .collect::<io::Result<Vec<_>>>()?
            .into_iter()
            .filter(|path| {
                path.file_name()
                    .and_then(|name| name.to_str())
                    .is_some_and(|name| {
                        name.starts_with(&format!("{LEDGER_FILE_PREFIX}."))
                            && name.ends_with(".jsonl")
                    })
            })
            .collect::<Vec<_>>(),
        Err(error) if error.kind() == io::ErrorKind::NotFound => return Ok(Vec::new()),
        Err(error) => return Err(error),
    };
    paths.sort();
    let mut records = Vec::new();
    for path in paths {
        let file = fs::File::open(&path)?;
        let source_day = ledger_source_day(&path);
        for (index, line) in BufReader::new(file).split(b'\n').enumerate() {
            let line = line?;
            if line.iter().all(u8::is_ascii_whitespace) {
                continue;
            }
            let record = match serde_json::from_slice::<ErrorRecord>(&line) {
                Ok(record) => {
                    if since.is_some_and(|since| record.recorded_at < since) {
                        continue;
                    }
                    record
                }
                Err(_) => {
                    // Only a source day wholly before the window proves this
                    // corruption historical. Unknown dates must remain visible.
                    if since.is_some_and(|since| source_day.is_some_and(|(_, end)| end <= since)) {
                        continue;
                    }
                    let file_name = sanitize_error_message(
                        &path.file_name().unwrap_or_default().to_string_lossy(),
                    );
                    let line_number = (index + 1).to_string();
                    let mut diagnostic = ErrorRecord::new_host(
                        ErrorKind::LedgerCorruption,
                        format!("Invalid error ledger row at {file_name}:{line_number}"),
                    )
                    .with_context(BTreeMap::from([
                        ("ledger_file".into(), file_name.clone()),
                        ("line".into(), line_number.clone()),
                    ]));
                    diagnostic.id = format!("ledger_corruption:{file_name}:{line_number}");
                    // A stable day anchor (or explicit unknown sentinel), never
                    // the read time. Keep uncertainty in the existing context.
                    diagnostic.recorded_at =
                        source_day.map_or(DateTime::<Utc>::UNIX_EPOCH, |(start, _)| start);
                    diagnostic.context.insert(
                        "source_time_precision".into(),
                        if source_day.is_some() {
                            "day"
                        } else {
                            "unknown"
                        }
                        .into(),
                    );
                    if let Some((start, end)) = source_day {
                        diagnostic
                            .context
                            .insert("source_day_start".into(), start.to_rfc3339());
                        diagnostic
                            .context
                            .insert("source_day_end_exclusive".into(), end.to_rfc3339());
                    }
                    diagnostic
                }
            };
            records.push(record);
        }
    }
    records.sort_by_key(|record| record.recorded_at);
    Ok(records)
}

fn ledger_source_day(path: &Path) -> Option<(DateTime<Utc>, DateTime<Utc>)> {
    let date = path
        .file_name()?
        .to_str()?
        .strip_prefix("errors.")?
        .strip_suffix(".jsonl")?;
    let day = NaiveDate::parse_from_str(date, "%Y-%m-%d").ok()?;
    if day.format("%Y-%m-%d").to_string() != date {
        return None;
    }
    Some((
        day.and_hms_opt(0, 0, 0)?.and_utc(),
        day.succ_opt()?.and_hms_opt(0, 0, 0)?.and_utc(),
    ))
}

fn json_io_error(error: serde_json::Error) -> io::Error {
    io::Error::other(error)
}

